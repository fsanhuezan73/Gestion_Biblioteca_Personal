-- Estadísticas y metas de lectura. Ejecutar después de 001–006.
-- Aplicar primero en un esquema Oracle de pruebas, nunca automáticamente.
-- Oracle confirma DDL implícitamente: un ROLLBACK no deshace esta migración.
-- No modifica datos existentes: todas las columnas nuevas son opcionales.

-- Fechas de lectura y número de páginas de cada libro.
ALTER TABLE books ADD (
    started_at  DATE,
    finished_at DATE,
    page_count  NUMBER(6),
    CONSTRAINT chk_books_reading_dates CHECK (
        started_at IS NULL OR finished_at IS NULL OR finished_at >= started_at
    ),
    CONSTRAINT chk_books_page_count CHECK (
        page_count IS NULL OR page_count BETWEEN 1 AND 100000
    )
);

COMMENT ON COLUMN books.started_at  IS 'Fecha en que se empezó a leer; NULL = desconocida';
COMMENT ON COLUMN books.finished_at IS 'Fecha en que se terminó de leer; NULL = desconocida o no terminado';
COMMENT ON COLUMN books.page_count  IS 'Número de páginas del libro (opcional)';

-- Acelera las estadísticas por año (libros terminados de cada usuario).
CREATE INDEX idx_books_user_finished ON books(user_id, finished_at);

-- Meta anual de libros por usuario: una sola meta por usuario y año.
CREATE TABLE reading_goals (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       NUMBER    NOT NULL,
    goal_year     NUMBER(4) NOT NULL,
    target_books  NUMBER(4) NOT NULL,
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_reading_goals_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uq_reading_goals_user_year UNIQUE (user_id, goal_year),
    CONSTRAINT chk_reading_goals_year CHECK (goal_year BETWEEN 1900 AND 2100),
    CONSTRAINT chk_reading_goals_target CHECK (target_books BETWEEN 1 AND 365)
);

COMMENT ON TABLE  reading_goals              IS 'Meta anual de libros leídos por usuario';
COMMENT ON COLUMN reading_goals.goal_year    IS 'Año calendario de la meta';
COMMENT ON COLUMN reading_goals.target_books IS 'Cantidad de libros que el usuario quiere terminar en el año';
